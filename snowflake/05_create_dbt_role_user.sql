USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS TRANSFORMER
  COMMENT = 'Role used by dbt to build staging and marts';

-- Lets SYSADMIN see and manage objects that dbt creates.
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;

CREATE USER IF NOT EXISTS DBT_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = TRANSFORMER
  DEFAULT_WAREHOUSE = CLAIMS_WH
  RSA_PUBLIC_KEY = 'PASTE_PUBLIC_KEY_HERE'
  COMMENT = 'Service user for dbt';

GRANT ROLE TRANSFORMER TO USER DBT_SVC;

USE ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE CLAIMS_WH TO ROLE TRANSFORMER;
GRANT USAGE ON DATABASE CLAIMS_DW TO ROLE TRANSFORMER;
GRANT CREATE SCHEMA ON DATABASE CLAIMS_DW TO ROLE TRANSFORMER;

-- Read access to raw data, including tables created later.
GRANT USAGE ON SCHEMA CLAIMS_DW.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA CLAIMS_DW.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA CLAIMS_DW.RAW TO ROLE TRANSFORMER;

-- Build access to the transformed layers.
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA CLAIMS_DW.STAGING TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA CLAIMS_DW.MARTS TO ROLE TRANSFORMER;

SHOW GRANTS TO ROLE TRANSFORMER;